/**
 * Filter preset locations by city id or all
 */
export function getLocationsByCity(cityId: string): LocationPoint[] {
  if (!cityId || cityId === 'all') {
    return PRESET_LOCATIONS.filter((loc) => loc.id !== 'loc-current');
  }
  return PRESET_LOCATIONS.filter((loc) => loc.city === cityId);
}
